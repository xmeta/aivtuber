//! The env file the local profile runs from (docs/local-profile-quickstart.adoc
//! step 4). `KEY=VALUE` per line, no quoting, `#` comments, UTF-8. The same
//! file is read by `aivtuber-setup start`; because values are unquoted it also
//! works with `docker run --env-file` style tools and is trivial to parse.
//!
//! The file holds two generated secrets (the memory pseudonym key and the
//! control secret). It is never overwritten without `--force`, is created
//! owner-only on Unix, and is never printed.

use std::fs::OpenOptions;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Where everything lives once provisioned.
#[derive(Debug, Clone)]
pub struct Paths {
    pub llama_server: PathBuf,
    pub llm_gguf: PathBuf,
    /// The vision projector of a multimodal profile.
    pub llm_mmproj: Option<PathBuf>,
    pub vad_model: PathBuf,
    pub stt_model_dir: PathBuf,
    pub tts_model_dir: PathBuf,
    pub tts_sidecar: PathBuf,
    pub speech_sidecar: PathBuf,
    pub stt_worker: PathBuf,
    pub app: PathBuf,
    pub pack_root: PathBuf,
    pub audio_root: PathBuf,
    pub avatar_page_dir: PathBuf,
}

#[derive(Debug, Clone)]
pub struct Secrets {
    pub pseudonym_key_hex: String,
    pub control_secret: String,
}

impl Secrets {
    pub fn generate() -> Result<Self, String> {
        let mut key = [0u8; 32];
        let mut secret = [0u8; 16];
        getrandom::fill(&mut key).map_err(|e| format!("no system randomness: {e}"))?;
        getrandom::fill(&mut secret).map_err(|e| format!("no system randomness: {e}"))?;
        Ok(Self {
            pseudonym_key_hex: crate::download::hex(&key),
            // 16 random bytes as 32 hex characters: exactly the 32 the app requires.
            control_secret: crate::download::hex(&secret),
        })
    }
}

/// What `start` uses when an older env file lacks the profile keys.
pub const LLAMA_ALIAS: &str = "qwen3-4b-instruct-2507";
pub const LLAMA_DEFAULT_CONTEXT: u32 = 4096;
/// A cold first start reads and hashes every pinned file from a possibly slow
/// or busy disk (docs/local-profile-quickstart.adoc, "Slow first start"); the
/// app's own default of 60 s then leaves no margin.
pub const TTS_READY_TIMEOUT_MS: u64 = 180_000;
pub const DEFAULT_LLAMA_PORT: u16 = 18080;
pub const TTS_PORT: u16 = 8770;
pub const AVATAR_PORT: u16 = 8765;

fn push(text: &mut String, key: &str, value: &str) {
    text.push_str(key);
    text.push('=');
    text.push_str(value);
    text.push('\n');
}

/// Who runs the language model.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LlmMode {
    /// `start` runs the pinned llama-server on loopback.
    Managed,
    /// The operator runs it; the app talks to this loopback URL.
    External(String),
    /// Skipped or not on disk: `start` refuses until this is fixed.
    Missing,
}

/// The profile-dependent part of the env file.
#[derive(Debug, Clone)]
pub struct LlmSetup {
    pub profile: String,
    pub alias: String,
    pub model_version: String,
    pub context: u32,
    pub parallel: Option<u32>,
    pub mode: LlmMode,
}

/// Accepts `http://<loopback>[:port][/path]`; an empty path becomes the
/// `/v1/responses` route the app calls. The app refuses anything that is not
/// loopback; this refuses it earlier, with the way out.
pub fn normalize_llm_endpoint(raw: &str) -> Result<String, String> {
    let url = url::Url::parse(raw).map_err(|e| format!("--llm-endpoint {raw:?}: {e}"))?;
    if url.scheme() != "http" {
        return Err(format!(
            "--llm-endpoint must be an http:// loopback URL, not {}://",
            url.scheme()
        ));
    }
    let loopback = match url.host() {
        Some(url::Host::Ipv4(ip)) => ip.is_loopback(),
        Some(url::Host::Ipv6(ip)) => ip.is_loopback(),
        Some(url::Host::Domain(d)) => d.eq_ignore_ascii_case("localhost"),
        None => false,
    };
    if !loopback || !url.username().is_empty() || url.password().is_some() {
        return Err("--llm-endpoint must be a loopback address (127.0.0.1, [::1] or localhost) without credentials; the local profile refuses any other endpoint".to_owned());
    }
    if url.query().is_some() || url.fragment().is_some() {
        return Err("--llm-endpoint must not carry a query or fragment".to_owned());
    }
    let mut url = url;
    if url.path() == "/" || url.path().is_empty() {
        url.set_path("/v1/responses");
    }
    Ok(url.to_string())
}

pub fn render(
    paths: &Paths,
    secrets: &Secrets,
    llama_port: u16,
    gpu_layers: u32,
    llm: &LlmSetup,
) -> String {
    let p = |path: &Path| path.display().to_string();
    let mut t = String::new();
    t.push_str("# Generated by `aivtuber-setup local` (docs/local-profile-quickstart.adoc).\n");
    t.push_str("# Holds two secrets: do not share or commit this file. KEY=VALUE, no quoting.\n");
    t.push_str("# Start the whole profile with `aivtuber-setup start`.\n\n");
    t.push_str("# profile and Thinking (llama-server on loopback)\n");
    push(&mut t, "AIVTUBER_MODE", "local");
    push(&mut t, "AIVTUBER_GENERATIVE_ENABLED", "true");
    push(&mut t, "AIVTUBER_OPENAI_AUTH", "unauthenticated-loopback");
    let endpoint = match &llm.mode {
        LlmMode::External(url) => url.clone(),
        _ => format!("http://127.0.0.1:{llama_port}/v1/responses"),
    };
    push(&mut t, "AIVTUBER_OPENAI_ENDPOINT", &endpoint);
    push(&mut t, "AIVTUBER_OPENAI_MODEL", &llm.alias);
    push(&mut t, "AIVTUBER_OPENAI_MODEL_VERSION", &llm.model_version);
    push(&mut t, "AIVTUBER_OPENAI_BACKEND_NAME", "llama-server");
    push(&mut t, "AIVTUBER_OPENAI_MAX_OUTPUT_TOKENS", "96");
    push(
        &mut t,
        "AIVTUBER_MEMORY_PSEUDONYM_KEY_HEX",
        &secrets.pseudonym_key_hex,
    );
    push(&mut t, "AIVTUBER_CONTROL_SECRET", &secrets.control_secret);
    t.push_str("\n# pack, audio\n");
    push(&mut t, "AIVTUBER_PACK_ROOT", &p(&paths.pack_root));
    push(&mut t, "AIVTUBER_AUDIO_ROOT", &p(&paths.audio_root));
    t.push_str("\n# local TTS (supervised child)\n");
    push(
        &mut t,
        "AIVTUBER_TTS_ENDPOINT",
        &format!("http://127.0.0.1:{TTS_PORT}/v1/synthesize"),
    );
    push(&mut t, "AIVTUBER_TTS_SIDECAR", &p(&paths.tts_sidecar));
    push(
        &mut t,
        "AIVTUBER_TTS_SIDECAR_MODEL_DIR",
        &p(&paths.tts_model_dir),
    );
    push(&mut t, "AIVTUBER_TTS_SIDECAR_AMPLITUDE_VISEMES", "true");
    push(
        &mut t,
        "AIVTUBER_TTS_SIDECAR_READY_TIMEOUT_MS",
        &TTS_READY_TIMEOUT_MS.to_string(),
    );
    t.push_str("\n# speech input (supervised children); the app splits ARGS on whitespace\n");
    push(&mut t, "AIVTUBER_SPEECH_SIDECAR", &p(&paths.speech_sidecar));
    push(
        &mut t,
        "AIVTUBER_SPEECH_SIDECAR_ARGS",
        &format!("--model {} --language ja", p(&paths.vad_model)),
    );
    push(&mut t, "AIVTUBER_SPEECH_STT_WORKER", &p(&paths.stt_worker));
    push(
        &mut t,
        "AIVTUBER_SPEECH_STT_MODEL_DIR",
        &p(&paths.stt_model_dir),
    );
    push(&mut t, "AIVTUBER_SPEECH_CONVERSATION", "true");
    push(&mut t, "AIVTUBER_SPEECH_FLOOR", "true");
    push(&mut t, "AIVTUBER_SPEECH_BARGE_IN", "true");
    t.push_str("\n# local avatar\n");
    push(&mut t, "AIVTUBER_AVATAR_OUTPUT", "local");
    push(
        &mut t,
        "AIVTUBER_LOCAL_AVATAR_PORT",
        &AVATAR_PORT.to_string(),
    );
    push(
        &mut t,
        "AIVTUBER_LOCAL_AVATAR_PAGE_DIR",
        &p(&paths.avatar_page_dir),
    );
    t.push_str("\n# untrusted-input ceiling\n");
    push(&mut t, "AIVTUBER_INGRESS_MAX_TRUST", "untrusted");
    push(
        &mut t,
        "AIVTUBER_INGRESS_SOURCE_CLASSES",
        "public_chat,speech",
    );
    t.push_str("\n# read by `aivtuber-setup start` only; the app ignores these\n");
    push(&mut t, "AIVTUBER_SETUP_APP", &p(&paths.app));
    push(&mut t, "AIVTUBER_SETUP_PROFILE", &llm.profile);
    let (mode, why) = match &llm.mode {
        LlmMode::Managed => ("managed", ""),
        LlmMode::External(_) => (
            "external",
            "# --llm-endpoint: you run the model server; `start` runs only the app.\n",
        ),
        LlmMode::Missing => (
            "missing",
            "# The model or llama-server was skipped or is not on disk, so `start` refuses.\n# Run `aivtuber-setup local` again without --skip, or pass --llm-endpoint <loopback url>.\n",
        ),
    };
    t.push_str(why);
    push(&mut t, "AIVTUBER_SETUP_LLAMA_MODE", mode);
    // Only a managed server has these; otherwise they are written commented out
    // so the file never points at a path that does not exist.
    let managed = llm.mode == LlmMode::Managed;
    let mut line = |key: &str, value: &str| {
        if !managed {
            t.push_str("# ");
        }
        push(&mut t, key, value);
    };
    line("AIVTUBER_SETUP_LLAMA_SERVER", &p(&paths.llama_server));
    line("AIVTUBER_SETUP_LLAMA_GGUF", &p(&paths.llm_gguf));
    if let Some(mmproj) = &paths.llm_mmproj {
        line("AIVTUBER_SETUP_LLAMA_MMPROJ", &p(mmproj));
    }
    line("AIVTUBER_SETUP_LLAMA_PORT", &llama_port.to_string());
    line("AIVTUBER_SETUP_LLAMA_GPU_LAYERS", &gpu_layers.to_string());
    line("AIVTUBER_SETUP_LLAMA_CONTEXT", &llm.context.to_string());
    if let Some(parallel) = llm.parallel {
        line("AIVTUBER_SETUP_LLAMA_PARALLEL", &parallel.to_string());
    }
    line("AIVTUBER_SETUP_LLAMA_ALIAS", &llm.alias);
    t
}

#[derive(Debug, PartialEq, Eq)]
pub enum WriteOutcome {
    Written,
    /// The file existed and `--force` was not given; nothing was touched.
    KeptExisting,
}

/// Creates the env file. An existing file is never replaced unless `force`.
pub fn write_env(path: &Path, content: &str, force: bool) -> Result<WriteOutcome, String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let mut options = OpenOptions::new();
    options.write(true);
    if force {
        options.create(true).truncate(true);
    } else {
        options.create_new(true); // refuses atomically if it exists
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    match options.open(path) {
        Ok(mut file) => {
            file.write_all(content.as_bytes())
                .map_err(|e| e.to_string())?;
            Ok(WriteOutcome::Written)
        }
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => Ok(WriteOutcome::KeptExisting),
        Err(e) => Err(format!("cannot write {}: {e}", path.display())),
    }
}

/// Parses `KEY=VALUE` lines (comments and blanks skipped; first `=` splits).
pub fn parse_env(text: &str) -> Vec<(String, String)> {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter_map(|l| {
            let (k, v) = l.split_once('=')?;
            let k = k.trim();
            (!k.is_empty()).then(|| (k.to_owned(), v.to_owned()))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn paths() -> Paths {
        let q = |s: &str| PathBuf::from(s);
        Paths {
            llama_server: q("/a/llama-server"),
            llm_gguf: q("/a/m.gguf"),
            llm_mmproj: None,
            vad_model: q("/a/vad.onnx"),
            stt_model_dir: q("/a/k2v2"),
            tts_model_dir: q("/a/tts"),
            tts_sidecar: q("/r/local-tts-sidecar"),
            speech_sidecar: q("/r/speech-vad-sidecar"),
            stt_worker: q("/r/speech-stt-worker"),
            app: q("/r/aivtuber-app"),
            pack_root: q("/r/pack"),
            audio_root: q("/r/pack/audio"),
            avatar_page_dir: q("/r/page"),
        }
    }

    fn scratch(tag: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("aivtuber-config-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn setup(mode: LlmMode) -> LlmSetup {
        LlmSetup {
            profile: "default".into(),
            alias: LLAMA_ALIAS.into(),
            model_version: "Q4_K_M".into(),
            context: 4096,
            parallel: None,
            mode,
        }
    }

    #[test]
    fn the_rendered_file_has_the_quickstart_keys_and_no_remote_credential() {
        let secrets = Secrets::generate().unwrap();
        assert_eq!(secrets.pseudonym_key_hex.len(), 64);
        assert_eq!(secrets.control_secret.len(), 32);
        let text = render(&paths(), &secrets, 18080, 99, &setup(LlmMode::Managed));
        let map: std::collections::BTreeMap<_, _> = parse_env(&text).into_iter().collect();
        assert_eq!(map["AIVTUBER_MODE"], "local");
        assert_eq!(map["AIVTUBER_OPENAI_AUTH"], "unauthenticated-loopback");
        assert_eq!(
            map["AIVTUBER_OPENAI_ENDPOINT"],
            "http://127.0.0.1:18080/v1/responses"
        );
        assert_eq!(map["AIVTUBER_OPENAI_MODEL"], LLAMA_ALIAS);
        assert_eq!(
            map["AIVTUBER_SPEECH_SIDECAR_ARGS"],
            "--model /a/vad.onnx --language ja"
        );
        assert_eq!(
            map["AIVTUBER_MEMORY_PSEUDONYM_KEY_HEX"],
            secrets.pseudonym_key_hex
        );
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_GPU_LAYERS"], "99");
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_MODE"], "managed");
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_CONTEXT"], "4096");
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_ALIAS"], LLAMA_ALIAS);
        assert_eq!(map["AIVTUBER_TTS_SIDECAR_READY_TIMEOUT_MS"], "180000");
        assert!(!map.contains_key("AIVTUBER_SETUP_LLAMA_PARALLEL"));
        assert!(!map.contains_key("AIVTUBER_SETUP_LLAMA_MMPROJ"));
        assert!(!map.keys().any(|k| k.contains("API_KEY")));
        // Both secrets are distinct per run.
        assert_ne!(
            secrets.control_secret,
            Secrets::generate().unwrap().control_secret
        );
    }

    #[test]
    fn a_vision_profile_writes_its_projector_slots_and_alias() {
        let mut p = paths();
        p.llm_mmproj = Some(PathBuf::from("/a/mmproj.gguf"));
        let mut s = setup(LlmMode::Managed);
        s.alias = "qwen3-vl-4b-instruct".into();
        s.context = 8192;
        s.parallel = Some(2);
        let text = render(&p, &Secrets::generate().unwrap(), 18080, 99, &s);
        let map: std::collections::BTreeMap<_, _> = parse_env(&text).into_iter().collect();
        assert_eq!(map["AIVTUBER_OPENAI_MODEL"], "qwen3-vl-4b-instruct");
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_ALIAS"], "qwen3-vl-4b-instruct");
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_MMPROJ"], "/a/mmproj.gguf");
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_CONTEXT"], "8192");
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_PARALLEL"], "2");
    }

    #[test]
    fn a_missing_model_is_commented_out_and_an_external_one_has_its_endpoint() {
        let secrets = Secrets::generate().unwrap();
        let text = render(&paths(), &secrets, 18080, 99, &setup(LlmMode::Missing));
        let map: std::collections::BTreeMap<_, _> = parse_env(&text).into_iter().collect();
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_MODE"], "missing");
        assert!(!map.keys().any(|k| k == "AIVTUBER_SETUP_LLAMA_GGUF"));
        assert!(text.contains("# AIVTUBER_SETUP_LLAMA_GGUF=/a/m.gguf"));
        assert!(text.contains("--llm-endpoint"));

        let url = "http://127.0.0.1:9000/v1/responses".to_owned();
        let text = render(
            &paths(),
            &secrets,
            18080,
            99,
            &setup(LlmMode::External(url.clone())),
        );
        let map: std::collections::BTreeMap<_, _> = parse_env(&text).into_iter().collect();
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_MODE"], "external");
        assert_eq!(map["AIVTUBER_OPENAI_ENDPOINT"], url);
        assert!(!map.contains_key("AIVTUBER_SETUP_LLAMA_SERVER"));
    }

    #[test]
    fn the_llm_endpoint_must_be_loopback_http() {
        assert_eq!(
            normalize_llm_endpoint("http://127.0.0.1:9000").unwrap(),
            "http://127.0.0.1:9000/v1/responses"
        );
        assert_eq!(
            normalize_llm_endpoint("http://localhost:9000/custom").unwrap(),
            "http://localhost:9000/custom"
        );
        assert!(normalize_llm_endpoint("http://[::1]:9000/").is_ok());
        for bad in [
            "https://127.0.0.1:9000",
            "http://example.com/v1/responses",
            "http://192.168.1.5:8080",
            "http://0.0.0.0:8080",
            "http://user:pw@127.0.0.1:9000",
            "http://127.0.0.1:9000/?key=1",
            "not a url",
        ] {
            assert!(normalize_llm_endpoint(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn an_existing_env_file_is_kept_unless_forced() {
        let dir = scratch("force");
        let path = dir.join("local-profile.env");
        assert_eq!(
            write_env(&path, "A=1\n", false).unwrap(),
            WriteOutcome::Written
        );
        assert_eq!(
            write_env(&path, "A=2\n", false).unwrap(),
            WriteOutcome::KeptExisting
        );
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "A=1\n");
        assert_eq!(
            write_env(&path, "A=3\n", true).unwrap(),
            WriteOutcome::Written
        );
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "A=3\n");
    }

    #[test]
    fn parse_env_skips_comments_and_splits_on_the_first_equals() {
        let parsed = parse_env("# c\n\nA=1\nB=x=y z\n  C = 3 \nnovalue\n");
        assert_eq!(
            parsed,
            vec![
                ("A".into(), "1".into()),
                ("B".into(), "x=y z".into()),
                ("C".into(), " 3".into()),
            ]
        );
    }
}
