//! The env file the local profile runs from (docs/local-profile-quickstart.adoc
//! step 4). `KEY=VALUE` per line, no quoting, `#` comments, UTF-8. The same
//! file is read by `aivtuber-setup start`; because values are unquoted it also
//! works with `docker run --env-file` style tools and is trivial to parse.
//!
//! The file holds two generated secrets (the memory pseudonym key and the
//! control secret). It is never overwritten without `--force`, is created
//! owner-only on Unix, and is never printed.

use std::fs::OpenOptions;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Where everything lives once provisioned.
#[derive(Debug, Clone)]
pub struct Paths {
    pub llama_server: PathBuf,
    pub llm_gguf: PathBuf,
    pub vad_model: PathBuf,
    pub stt_model_dir: PathBuf,
    pub tts_model_dir: PathBuf,
    pub tts_sidecar: PathBuf,
    pub speech_sidecar: PathBuf,
    pub stt_worker: PathBuf,
    pub app: PathBuf,
    pub pack_root: PathBuf,
    pub audio_root: PathBuf,
    pub avatar_page_dir: PathBuf,
}

#[derive(Debug, Clone)]
pub struct Secrets {
    pub pseudonym_key_hex: String,
    pub control_secret: String,
}

impl Secrets {
    pub fn generate() -> Result<Self, String> {
        let mut key = [0u8; 32];
        let mut secret = [0u8; 16];
        getrandom::fill(&mut key).map_err(|e| format!("no system randomness: {e}"))?;
        getrandom::fill(&mut secret).map_err(|e| format!("no system randomness: {e}"))?;
        Ok(Self {
            pseudonym_key_hex: crate::download::hex(&key),
            // 16 random bytes as 32 hex characters: exactly the 32 the app requires.
            control_secret: crate::download::hex(&secret),
        })
    }
}

pub const LLAMA_ALIAS: &str = "qwen3-4b-instruct-2507";
pub const DEFAULT_LLAMA_PORT: u16 = 18080;
pub const TTS_PORT: u16 = 8770;
pub const AVATAR_PORT: u16 = 8765;

fn push(text: &mut String, key: &str, value: &str) {
    text.push_str(key);
    text.push('=');
    text.push_str(value);
    text.push('\n');
}

pub fn render(paths: &Paths, secrets: &Secrets, llama_port: u16, gpu_layers: u32) -> String {
    let p = |path: &Path| path.display().to_string();
    let mut t = String::new();
    t.push_str("# Generated by `aivtuber-setup local` (docs/local-profile-quickstart.adoc).\n");
    t.push_str("# Holds two secrets: do not share or commit this file. KEY=VALUE, no quoting.\n");
    t.push_str("# Start the whole profile with `aivtuber-setup start`.\n\n");
    t.push_str("# profile and Thinking (llama-server on loopback)\n");
    push(&mut t, "AIVTUBER_MODE", "local");
    push(&mut t, "AIVTUBER_GENERATIVE_ENABLED", "true");
    push(&mut t, "AIVTUBER_OPENAI_AUTH", "unauthenticated-loopback");
    push(
        &mut t,
        "AIVTUBER_OPENAI_ENDPOINT",
        &format!("http://127.0.0.1:{llama_port}/v1/responses"),
    );
    push(&mut t, "AIVTUBER_OPENAI_MODEL", LLAMA_ALIAS);
    push(&mut t, "AIVTUBER_OPENAI_MODEL_VERSION", "Q4_K_M");
    push(&mut t, "AIVTUBER_OPENAI_BACKEND_NAME", "llama-server");
    push(&mut t, "AIVTUBER_OPENAI_MAX_OUTPUT_TOKENS", "96");
    push(
        &mut t,
        "AIVTUBER_MEMORY_PSEUDONYM_KEY_HEX",
        &secrets.pseudonym_key_hex,
    );
    push(&mut t, "AIVTUBER_CONTROL_SECRET", &secrets.control_secret);
    t.push_str("\n# pack, audio\n");
    push(&mut t, "AIVTUBER_PACK_ROOT", &p(&paths.pack_root));
    push(&mut t, "AIVTUBER_AUDIO_ROOT", &p(&paths.audio_root));
    t.push_str("\n# local TTS (supervised child)\n");
    push(
        &mut t,
        "AIVTUBER_TTS_ENDPOINT",
        &format!("http://127.0.0.1:{TTS_PORT}/v1/synthesize"),
    );
    push(&mut t, "AIVTUBER_TTS_SIDECAR", &p(&paths.tts_sidecar));
    push(
        &mut t,
        "AIVTUBER_TTS_SIDECAR_MODEL_DIR",
        &p(&paths.tts_model_dir),
    );
    push(&mut t, "AIVTUBER_TTS_SIDECAR_AMPLITUDE_VISEMES", "true");
    t.push_str("\n# speech input (supervised children); the app splits ARGS on whitespace\n");
    push(&mut t, "AIVTUBER_SPEECH_SIDECAR", &p(&paths.speech_sidecar));
    push(
        &mut t,
        "AIVTUBER_SPEECH_SIDECAR_ARGS",
        &format!("--model {} --language ja", p(&paths.vad_model)),
    );
    push(&mut t, "AIVTUBER_SPEECH_STT_WORKER", &p(&paths.stt_worker));
    push(
        &mut t,
        "AIVTUBER_SPEECH_STT_MODEL_DIR",
        &p(&paths.stt_model_dir),
    );
    push(&mut t, "AIVTUBER_SPEECH_CONVERSATION", "true");
    push(&mut t, "AIVTUBER_SPEECH_FLOOR", "true");
    push(&mut t, "AIVTUBER_SPEECH_BARGE_IN", "true");
    t.push_str("\n# local avatar\n");
    push(&mut t, "AIVTUBER_AVATAR_OUTPUT", "local");
    push(
        &mut t,
        "AIVTUBER_LOCAL_AVATAR_PORT",
        &AVATAR_PORT.to_string(),
    );
    push(
        &mut t,
        "AIVTUBER_LOCAL_AVATAR_PAGE_DIR",
        &p(&paths.avatar_page_dir),
    );
    t.push_str("\n# untrusted-input ceiling\n");
    push(&mut t, "AIVTUBER_INGRESS_MAX_TRUST", "untrusted");
    push(
        &mut t,
        "AIVTUBER_INGRESS_SOURCE_CLASSES",
        "public_chat,speech",
    );
    t.push_str("\n# read by `aivtuber-setup start` only; the app ignores these\n");
    push(&mut t, "AIVTUBER_SETUP_APP", &p(&paths.app));
    push(
        &mut t,
        "AIVTUBER_SETUP_LLAMA_SERVER",
        &p(&paths.llama_server),
    );
    push(&mut t, "AIVTUBER_SETUP_LLAMA_GGUF", &p(&paths.llm_gguf));
    push(&mut t, "AIVTUBER_SETUP_LLAMA_PORT", &llama_port.to_string());
    push(
        &mut t,
        "AIVTUBER_SETUP_LLAMA_GPU_LAYERS",
        &gpu_layers.to_string(),
    );
    t
}

#[derive(Debug, PartialEq, Eq)]
pub enum WriteOutcome {
    Written,
    /// The file existed and `--force` was not given; nothing was touched.
    KeptExisting,
}

/// Creates the env file. An existing file is never replaced unless `force`.
pub fn write_env(path: &Path, content: &str, force: bool) -> Result<WriteOutcome, String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let mut options = OpenOptions::new();
    options.write(true);
    if force {
        options.create(true).truncate(true);
    } else {
        options.create_new(true); // refuses atomically if it exists
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    match options.open(path) {
        Ok(mut file) => {
            file.write_all(content.as_bytes())
                .map_err(|e| e.to_string())?;
            Ok(WriteOutcome::Written)
        }
        Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => Ok(WriteOutcome::KeptExisting),
        Err(e) => Err(format!("cannot write {}: {e}", path.display())),
    }
}

/// Parses `KEY=VALUE` lines (comments and blanks skipped; first `=` splits).
pub fn parse_env(text: &str) -> Vec<(String, String)> {
    text.lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .filter_map(|l| {
            let (k, v) = l.split_once('=')?;
            let k = k.trim();
            (!k.is_empty()).then(|| (k.to_owned(), v.to_owned()))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn paths() -> Paths {
        let q = |s: &str| PathBuf::from(s);
        Paths {
            llama_server: q("/a/llama-server"),
            llm_gguf: q("/a/m.gguf"),
            vad_model: q("/a/vad.onnx"),
            stt_model_dir: q("/a/k2v2"),
            tts_model_dir: q("/a/tts"),
            tts_sidecar: q("/r/local-tts-sidecar"),
            speech_sidecar: q("/r/speech-vad-sidecar"),
            stt_worker: q("/r/speech-stt-worker"),
            app: q("/r/aivtuber-app"),
            pack_root: q("/r/pack"),
            audio_root: q("/r/pack/audio"),
            avatar_page_dir: q("/r/page"),
        }
    }

    fn scratch(tag: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("aivtuber-config-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn the_rendered_file_has_the_quickstart_keys_and_no_remote_credential() {
        let secrets = Secrets::generate().unwrap();
        assert_eq!(secrets.pseudonym_key_hex.len(), 64);
        assert_eq!(secrets.control_secret.len(), 32);
        let text = render(&paths(), &secrets, 18080, 99);
        let map: std::collections::BTreeMap<_, _> = parse_env(&text).into_iter().collect();
        assert_eq!(map["AIVTUBER_MODE"], "local");
        assert_eq!(map["AIVTUBER_OPENAI_AUTH"], "unauthenticated-loopback");
        assert_eq!(
            map["AIVTUBER_OPENAI_ENDPOINT"],
            "http://127.0.0.1:18080/v1/responses"
        );
        assert_eq!(map["AIVTUBER_OPENAI_MODEL"], LLAMA_ALIAS);
        assert_eq!(
            map["AIVTUBER_SPEECH_SIDECAR_ARGS"],
            "--model /a/vad.onnx --language ja"
        );
        assert_eq!(
            map["AIVTUBER_MEMORY_PSEUDONYM_KEY_HEX"],
            secrets.pseudonym_key_hex
        );
        assert_eq!(map["AIVTUBER_SETUP_LLAMA_GPU_LAYERS"], "99");
        assert!(!map.keys().any(|k| k.contains("API_KEY")));
        // Both secrets are distinct per run.
        assert_ne!(
            secrets.control_secret,
            Secrets::generate().unwrap().control_secret
        );
    }

    #[test]
    fn an_existing_env_file_is_kept_unless_forced() {
        let dir = scratch("force");
        let path = dir.join("local-profile.env");
        assert_eq!(
            write_env(&path, "A=1\n", false).unwrap(),
            WriteOutcome::Written
        );
        assert_eq!(
            write_env(&path, "A=2\n", false).unwrap(),
            WriteOutcome::KeptExisting
        );
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "A=1\n");
        assert_eq!(
            write_env(&path, "A=3\n", true).unwrap(),
            WriteOutcome::Written
        );
        assert_eq!(std::fs::read_to_string(&path).unwrap(), "A=3\n");
    }

    #[test]
    fn parse_env_skips_comments_and_splits_on_the_first_equals() {
        let parsed = parse_env("# c\n\nA=1\nB=x=y z\n  C = 3 \nnovalue\n");
        assert_eq!(
            parsed,
            vec![
                ("A".into(), "1".into()),
                ("B".into(), "x=y z".into()),
                ("C".into(), " 3".into()),
            ]
        );
    }
}
